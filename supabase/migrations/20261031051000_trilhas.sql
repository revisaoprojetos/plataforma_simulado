-- TRILHAS (learning path) — Estúdio de Conteúdo, área top-level. É NOVO.
-- ATENÇÃO: "trilha" em outras partes do código é OUTRA coisa (trilha de simulados em lib/aluno/trilhas.ts,
-- sequência de leitura em lib/leitura/trilha.ts, cronograma adaptativo em lib/cronograma). Esta é a trilha
-- do Estúdio: uma sequência ordenada de PRODUTOS (cursos/extensivos) com liberação relativa à matrícula.
-- RLS por tenant igual ao restante (ver 20261027000000_flashcards.sql).
--
-- NÃO aplicar automaticamente. Aplicar manualmente e rodar: NOTIFY pgrst, 'reload schema';

-- ─────────────────────────── 1) Trilha ───────────────────────────
create table if not exists simulado_trilhas (
  id                 uuid primary key default gen_random_uuid(),
  tenant_id          uuid not null,
  -- Código numérico amigável (exibido como "cód. 58"). Identity GLOBAL — estável e simples.
  codigo             bigint generated by default as identity,
  nome               text not null,
  slug               text,
  descricao          text,
  visibilidade       text not null default 'publica',   -- publica | privada | nao_listada
  trilha_anterior_id uuid references simulado_trilhas(id) on delete set null,
  bloquear_ordem     boolean not null default false,    -- aluno só abre o próximo após concluir o anterior
  bloquear_acesso_anterior boolean not null default false, -- bloquear acesso antes de terminar a trilha anterior
  ordem_modo         text not null default 'manual',    -- manual | data (liberação por offset de dias)
  banner_url         text,
  banner_tipo        text default 'imagem',             -- imagem | video
  conquista_url      text,                               -- imagem exibida ao concluir a trilha
  criado_por         uuid,
  criado_em          timestamptz not null default now(),
  atualizado_em      timestamptz not null default now(),
  -- Soft delete (Lixeira): o L0 deve incluir 'simulado_trilhas' em SOFT_DELETE_TABELAS.
  deletado           boolean not null default false,
  deletado_em        timestamptz,
  deletado_por       uuid
);

create index if not exists idx_trilhas_tenant on simulado_trilhas (tenant_id, deletado);
create unique index if not exists uq_trilhas_slug on simulado_trilhas (tenant_id, slug) where slug is not null and deletado = false;

alter table simulado_trilhas enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='simulado_trilhas' and policyname='trilhas_tenant') then
    create policy trilhas_tenant on simulado_trilhas
      using (tenant_id = current_setting('app.current_tenant_id', true)::uuid);
  end if;
end $$;

-- ─────────────────────────── 2) Itens da trilha (produtos ordenados) ───────────────────────────
create table if not exists simulado_trilha_itens (
  id                   uuid primary key default gen_random_uuid(),
  tenant_id            uuid not null,
  trilha_id            uuid not null references simulado_trilhas(id) on delete cascade,
  produto_id           uuid not null,                   -- simulado_produtos.id (curso/extensivo)
  ordem                int not null default 0,
  -- Liberação relativa à matrícula: null/0 = "na matrícula"; N = "+N dias" (modo 'data').
  liberacao_offset_dias int,
  criado_em            timestamptz not null default now(),
  unique (trilha_id, produto_id)
);

create index if not exists idx_trilha_itens on simulado_trilha_itens (tenant_id, trilha_id, ordem);

alter table simulado_trilha_itens enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='simulado_trilha_itens' and policyname='trilha_itens_tenant') then
    create policy trilha_itens_tenant on simulado_trilha_itens
      using (tenant_id = current_setting('app.current_tenant_id', true)::uuid);
  end if;
end $$;

